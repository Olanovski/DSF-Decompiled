function onlineGetNumberOfIconPacks()
  return #onlineIconData
end
_G.onlineGetNumberOfIconPacks = onlineGetNumberOfIconPacks
function onlineGetIconPackName(packIndex)
  if onlineIconData[packIndex] then
    return onlineIconData[packIndex].name
  end
  return "INVALID ICON INDEX - GET NAME"
end
_G.onlineGetIconPackName = onlineGetIconPackName
function onlineIsIconPackUnlocked(packIndex)
  if onlineIconData[packIndex] then
    return onlineIconData[packIndex].unlocked
  end
  print("onlineIsIconPackUnlocked: ICON INDEX " .. tostring(packIndex) .. " IS NOT VALID")
  return false
end
_G.onlineIsIconPackUnlocked = onlineIsIconPackUnlocked
function onlineIsIconPackNewlyUnlocked(packIndex)
  if onlineIconData[packIndex] then
    return onlineIconData[packIndex].new
  end
  print("onlineIsIconPackNewlyUnlocked: ICON INDEX " .. tostring(packIndex) .. " IS NOT VALID")
  return false
end
_G.onlineIsIconPackNewlyUnlocked = onlineIsIconPackNewlyUnlocked
function onlineIsAnyIconPackNewlyUnlocked()
  for i, pack in ipairs(onlineIconData) do
    if onlineIsIconPackNewlyUnlocked(i) == true then
      return true
    end
  end
  return false
end
_G.onlineIsAnyIconPackNewlyUnlocked = onlineIsAnyIconPackNewlyUnlocked
function onlineIconPackClearNew(packIndex)
  if onlineIconData[packIndex] then
    onlineIconData[packIndex].new = false
    return true
  end
  print("onlineIconPackClearNew: ICON INDEX " .. tostring(packIndex) .. " IS NOT VALID")
  return false
end
_G.onlineIconPackClearNew = onlineIconPackClearNew
function onlineGetNumOfIconsInPack(packIndex)
  if onlineIconData[packIndex] then
    return onlineIconData[packIndex].iconCount
  end
  print("onlineGetNumOfIconsInPack: ICON INDEX " .. tostring(packIndex) .. " IS NOT VALID")
  return -1
end
_G.onlineGetNumOfIconsInPack = onlineGetNumOfIconsInPack
function onlineGetIsIconPackLarge(packIndex)
  if onlineIconData[packIndex] then
    return onlineIconData[packIndex].iconCount > 8
  end
  print("onlineGetIsIconPackLarge: ICON INDEX " .. tostring(packIndex) .. " IS NOT VALID")
  return false
end
_G.onlineGetIsIconPackLarge = onlineGetIsIconPackLarge
function onlineGetIconIDInPack(packIndex, iconIndex)
  if onlineIconData[packIndex] and iconIndex <= onlineIconData[packIndex].iconCount then
    return onlineIconData[packIndex].startID + (iconIndex - 1)
  end
  print("onlineGetIconIDInPack: ICON INDEX " .. tostring(iconIndex) .. " IS NOT VALID or ICON TABLE INDEX IS " .. tostring(packIndex) .. " INVALID")
  return defaultIconID
end
_G.onlineGetIconIDInPack = onlineGetIconIDInPack
function onlineGetIconResourceName(iconID)
  for i, pack in ipairs(onlineIconData) do
    if iconID >= pack.startID and iconID < pack.startID + pack.iconCount and pack.resourceKeys[iconID - pack.startID + 1] then
      return pack.resourcePrefix .. "_" .. pack.resourceKeys[iconID - pack.startID + 1]
    end
  end
  print("onlineGetIconPackResourceName: ICON INDEX " .. tostring(iconID) .. " IS NOT VALID")
  return defaultIconResource
end
_G.onlineGetIconPackResourceName = onlineGetIconResourceName
function getIconLevelRequirement(index)
  return getLevelRequirementForUnlock(onlineIconData, index)
end
_G.getIconLevelRequirement = getIconLevelRequirement
