local getCurrentChapter = function()
  local currentProgression = ProfileSettings.GetProgression()
  if challengeProgressionTable and challengeProgressionTable[currentProgression] and challengeProgressionTable[currentProgression].settings then
    return challengeProgressionTable[currentProgression].settings.chapter
  end
end
local lastHint
function requestLoadingScreenHint()
  local appropriateHints = {}
  local playerLevel = ProfileSettings.GetMultiplayerProgressionLevel()
  local chapter = getCurrentChapter()
  local platform = framework.getPlatform()
  local PCPlatformID = 2
  hintType = hintType or "story"
  for i, data in ipairs(loadingScreenHints) do
    if data[hintType] and (not lastHint or lastHint and data.hint ~= lastHint.hint) then
      if hintType == "multiplayer" then
        if (not data.minLevel or playerLevel >= data.minLevel) and (not data.maxLevel or playerLevel <= data.maxLevel) then
          if platform == PCPlatformID then
            if not data.blockOnPC then
              table.insert(appropriateHints, {
                title = data.title,
                hint = data.hint
              })
            end
          else
            table.insert(appropriateHints, {
              title = data.title,
              hint = data.hint
            })
          end
        end
      elseif not data.minChapter or data.minChapter and chapter and chapter >= data.minChapter then
        if platform == PCPlatformID then
          if not data.blockOnPC then
            table.insert(appropriateHints, {
              title = data.title,
              hint = data.hint
            })
          end
        else
          table.insert(appropriateHints, {
            title = data.title,
            hint = data.hint
          })
        end
      end
    end
  end
  local randomlyChosenHint
  if #appropriateHints > 0 then
    randomlyChosenHint = appropriateHints[framework.random(1, #appropriateHints)]
  elseif lastHint then
    randomlyChosenHint = lastHint
    print("THERE ARE NO FURTHER HINTS THAT CAN BE RETURNED - RETURNING THE PREVIOUS HINT")
  else
    print("THERE ARE NO APPROPRIATE HINTS AND THERE IS NOT A PREVIOUS HINT TO RETURN - RETURNING FIRST HINT IN LIST")
    randomlyChosenHint = loadingScreenHints[1]
  end
  lastHint = randomlyChosenHint
  return randomlyChosenHint.title, randomlyChosenHint.hint
end
