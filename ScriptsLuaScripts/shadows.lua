function RegisterShadowClient(clientName)
  local settings = shadowSettings.default[clientName]
  if shadowSettings[configSelector.launchConfig.Name] then
    settings = shadowSettings[configSelector.launchConfig.Name][clientName]
  end
  local client = Shadows.Get(clientName)
  client:SetLightOffsets(lightOffsetsTable)
  if settings.enable then
    client:Enable()
    for k, v in next, settings, nil do
      if k ~= "enable" then
        client[k](client, v)
      end
    end
  else
    client:Disable()
  end
end
